function f(key, required, type, notes = "", example = "") {
  return {
    key,
    label: key,
    type,
    required,
    allowed: notes.includes("|") ? notes : "",
    notes: notes.includes("|") ? "" : notes,
    example,
    source: required === "Calculé" ? "Calculé" : "Saisie gérant",
    replacement: required === "Calculé" ? "Préservé" : "Remplacé",
    fill: required === "Calculé" ? "non" : required === "Requis" ? "oui" : "oui",
  };
}

function meta(replacement = "À faire") {
  return {
    key: "Statut_migration",
    label: "Statut_migration",
    type: "Liste",
    required: "Optionnel",
    allowed: "À faire|En cours|Validé|Ignoré",
    default: "À faire",
    source: "Saisie gérant",
    replacement,
    fill: "oui",
  };
}

